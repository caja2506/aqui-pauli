// Hosted Payment Page. Requests and responses are validated on the server.
// https://tilopay.com/developers/api/hosted-payment-page/process-payment
// https://tilopay.com/developers/api/procesos-operativos/consult
const crypto = require("node:crypto");
const { parseMinorCRC, minorToCRC, formatMinorCRC } = require("./paymentMoney");

const TILOPAY_BASE = "https://app.tilopay.com";
const PROVINCE_ISO = {
  "san josé": "CR-SJ", "san jose": "CR-SJ", alajuela: "CR-A", cartago: "CR-C", heredia: "CR-H",
  guanacaste: "CR-G", puntarenas: "CR-P", limón: "CR-L", limon: "CR-L",
};
let cachedToken = null;

async function tpFetch(path, { token, body, fetchFn = fetch } = {}) {
  if (typeof path !== "string" || !/^\/api\/v1\/[A-Za-z]+$/.test(path)) throw new Error("Ruta Tilopay inválida.");
  const headers = { Accept: "application/json", "Content-Type": "application/json" };
  if (token) headers.Authorization = `bearer ${token}`;
  const res = await fetchFn(`${TILOPAY_BASE}${path}`, {
    method: "POST", headers, body: JSON.stringify(body || {}), signal: AbortSignal.timeout(20000),
  });
  try {
    return { ok: res.ok, status: res.status, data: await res.json(), jsonValid: true, parseError: false };
  } catch {
    // A malformed response is unknown, never "no transaction" or a definitive rejection.
    return { ok: res.ok, status: res.status, data: null, jsonValid: false, parseError: true };
  }
}

async function getToken({ apiUser, password, fetchFn = fetch, now = Date.now() }) {
  if (typeof apiUser !== "string" || !apiUser || typeof password !== "string" || !password) throw new Error("Credenciales Tilopay incompletas.");
  const credentialId = crypto.createHash("sha256").update(`${apiUser}\0${password}`).digest("hex");
  if (cachedToken && cachedToken.credentialId === credentialId && cachedToken.exp > now) return cachedToken.token;
  const res = await tpFetch("/api/v1/login", { body: { apiuser: apiUser, password }, fetchFn });
  const token = res.data?.access_token;
  const rawTtl = res.data?.expires_in;
  const ttl = typeof rawTtl === "number" || (typeof rawTtl === "string" && /^\d+$/.test(rawTtl))
    ? Number(rawTtl) : NaN;
  if (!res.ok || !res.jsonValid || typeof token !== "string" || !token
      || !Number.isSafeInteger(ttl) || ttl <= 0) throw new Error(`Tilopay login ${res.status}`);
  cachedToken = { token, credentialId, exp: now + Math.max(0, ttl - 300) * 1000 };
  return token;
}
function clearTokenCache() { cachedToken = null; }
function formatAmountCRC(value) { return formatMinorCRC(parseMinorCRC(value)); }
const clean = (value, max = 100) => String(value || "").replace(/\s+/g, " ").trim().slice(0, max);
function splitName(full) {
  const parts = clean(full).split(" ").filter(Boolean);
  if (!parts.length) return { first: "Cliente", last: "Aqui Pauli" };
  if (parts.length === 1) return { first: parts[0], last: "-" };
  const mid = Math.ceil(parts.length / 2);
  return { first: parts.slice(0, mid).join(" "), last: parts.slice(mid).join(" ") };
}

/** token must be generated by the server for the payment attempt, never client orderNumber. */
function tilopayReference(token, attempt) {
  if (typeof token !== "string" || !/^[A-Za-z0-9]{8,64}$/.test(token)) throw new Error("Token de intento inválido.");
  if (!Number.isSafeInteger(attempt) || attempt < 1) throw new Error("Intento inválido.");
  return `AP-${token}-T${attempt}`;
}

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (isObject(value)) return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stable(value[key])]));
  return value;
}
/** Compatibility helper. The caller must supply the canonical server-priced order. */
function orderVersion(order) {
  if (!isObject(order)) throw new TypeError("Pedido inválido.");
  const lines = (Array.isArray(order.itemsSummary) ? order.itemsSummary : []).map((line) => {
    if (!isObject(line) || !Number.isSafeInteger(line.quantity) || line.quantity < 1) throw new Error("Línea de pedido inválida.");
    return [String(line.productId ?? ""), String(line.variantId ?? ""), line.quantity,
      parseMinorCRC(line.unitPrice ?? line.price, { allowZero: true }),
      line.lineTotal === undefined ? null : parseMinorCRC(line.lineTotal, { allowZero: true })];
  }).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b), "en"));
  const canon = {
    totalMinor: parseMinorCRC(order.total ?? 0, { allowZero: true }),
    subtotalMinor: parseMinorCRC(order.subtotal ?? 0, { allowZero: true }),
    shippingCostMinor: parseMinorCRC(order.shippingCost ?? 0, { allowZero: true }),
    shippingType: String(order.shippingType || ""), shippingAddress: stable(order.shippingAddress || {}), lines,
  };
  return crypto.createHash("sha256").update(JSON.stringify(canon)).digest("hex");
}

function buildProcessPayload({ key, redirect, orderId, order, orderNumber, amountMinor, crcTotal }) {
  const minor = amountMinor === undefined ? parseMinorCRC(crcTotal) : amountMinor;
  const amount = formatMinorCRC(minor);
  if (minor <= 0) throw new Error("Monto inválido.");
  if (typeof key !== "string" || !key || typeof orderId !== "string" || !orderId) throw new Error("Pago incompleto.");
  if (typeof orderNumber !== "string" || !/^[A-Za-z0-9-]{1,128}$/.test(orderNumber)) throw new Error("Referencia de pago inválida.");
  const { first, last } = splitName(order.customerName);
  const addr = order.shippingAddress || {};
  const state = PROVINCE_ISO[String(addr.provincia || "").trim().toLowerCase()] || "CR-SJ";
  const common = {
    Address: clean(addr.señas, 120) || "Costa Rica", Address2: clean(addr.distrito, 60) || "-",
    City: clean(addr.canton, 60) || "-", State: state,
    ZipPostCode: String(addr.codigoPostal || "10101").replace(/\D/g, "").slice(0, 5) || "10101",
    Country: "CR", Telephone: String(order.customerPhone || "").replace(/\D/g, "").slice(-8) || "00000000",
  };
  const payload = {
    redirect, key, amount, currency: "CRC", orderNumber, capture: "1", subscription: "0", platform: "api",
    returnData: Buffer.from(orderId).toString("base64"), token_version: "v2",
    billToFirstName: first, billToLastName: last, billToEmail: clean(order.customerEmail, 120),
    shipToFirstName: first, shipToLastName: last,
  };
  for (const [field, value] of Object.entries(common)) {
    payload[`billTo${field}`] = value;
    payload[`shipTo${field}`] = value;
  }
  return payload;
}

function classifyEnvironment(value) {
  if (typeof value !== "string") return null;
  const env = value.trim().toLowerCase();
  if (env === "test") return "test";
  if (env === "prod" || env === "production") return "live";
  return null;
}

function normalizeTransactionId(value) {
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value) || value <= 0) return null;
    return String(value);
  }
  if (typeof value !== "string" || !/^[1-9]\d{0,39}$/.test(value)) return null;
  return value; // Do not strip characters or convert large string IDs to Number.
}

function identity(value) {
  if (typeof value === "number") return Number.isSafeInteger(value) && value >= 0 ? String(value) : null;
  return typeof value === "string" && value.length > 0 && value.length <= 128 && !/\s/.test(value) ? value : null;
}

function matchesOrderNumber(value, original, orderPrefix = "", mode = "live") {
  if (typeof value !== "string" || typeof original !== "string" || !original) return false;
  if (value === original) return true;
  if (typeof orderPrefix === "string" && /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/.test(orderPrefix)
      && value === `${orderPrefix}-${original}`) return true;
  // Test integrations may not expose their merchant prefix yet. This exception
  // never applies to live attempts and still requires the full original reference.
  if (mode !== "test" || !value.endsWith(`-${original}`)) return false;
  const prefix = value.slice(0, -(original.length + 1));
  return /^[A-Za-z0-9]{1,64}$/.test(prefix);
}

function hasErrorPayload(data) {
  return ["error", "message", "result"].some((field) => {
    const value = data[field];
    return value !== undefined && value !== null && value !== "";
  });
}
function validConsultEnvelope(data) {
  return isObject(data) && (data.type === 200 || data.type === "200")
    && Array.isArray(data.response) && !hasErrorPayload(data);
}
function explicitMissingOrder(data) {
  return isObject(data) && (data.type === 200 || data.type === "200")
    && Array.isArray(data.response) && data.response.length === 0
    && typeof data.message === "string" && /^does not exist[.!]?$/i.test(data.message.trim())
    && !hasErrorPayload({ ...data, message: "" });
}
/** Absence at query time does not prove that a previously issued hosted URL cannot be paid later. */
function looksNotFound(data) {
  return explicitMissingOrder(data) || (validConsultEnvelope(data) && data.response.length === 0);
}

function isValidPaymentUrl(value) {
  if (typeof value !== "string") return false;
  try {
    const url = new URL(value);
    const suffix = ".tilopay.com";
    const host = url.hostname;
    const labels = host.endsWith(suffix) ? host.slice(0, -suffix.length).split(".") : [];
    return url.protocol === "https:" && !url.username && !url.password && (!url.port || url.port === "443")
      && host.length <= 253 && labels.length > 0
      && labels.every((label) => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label));
  } catch { return false; }
}

// Retain only bounded diagnostic metadata. The provider can echo integration
// keys, addresses or the hosted form URL in its message.
function processPaymentOutcome(response, error, sent) {
  const http = Number.isInteger(response?.status) ? response.status : null;
  const type = /^[0-9]{3}$/.test(String(response?.data?.type)) ? String(response.data.type) : null;
  const message = typeof response?.data?.message === "string" ? response.data.message : "";
  const field = message.match(/\b(redirect|key|amount|currency|orderNumber|capture|subscription|platform|hashVersion|token_version|(?:billTo|shipTo)(?:FirstName|LastName|Address2?|City|State|ZipPostCode|Country|Telephone|Email))\b/i)?.[1];
  let reason;
  if (!sent) reason = "REQUEST_BUILD_FAILED";
  else if (error || !response) reason = "TRANSPORT_UNKNOWN";
  else if (response.jsonValid === false) reason = "INVALID_RESPONSE";
  else if (http >= 500) reason = "PROVIDER_UNAVAILABLE";
  else if (http === 402 && type === "402" && /^the commerce has a transaction block[.!]?$/i.test(message.trim())) reason = "MERCHANT_TRANSACTION_BLOCK";
  else if (!response.ok || ["300", "400", "402", "403"].includes(type)) reason = "PROVIDER_REJECTED";
  else if (type !== "100") reason = "UNEXPECTED_RESPONSE";
  else if (!response.data.url) reason = "FORM_URL_MISSING";
  else if (!isValidPaymentUrl(response.data.url)) reason = "FORM_URL_INVALID";
  else reason = "FORM_READY";
  return { reason, http, type, ...(field ? { field } : {}) };
}

/**
 * Only matching, coherent, captured Payment evidence may credit an order.
 * Unknown/contradictory fields remain pending. This function never calls capture or trusts browser data.
 * returnedOrderNumber is deliberately not used to expand the permitted identity.
 */
function interpretConsult(data, {
  orderNumber, amountMinor, amount, crcTotal, mode, merchantId, orderPrefix = "",
} = {}) {
  const pending = (reason, tx, env) => ({ state: "pending_reconciliation", reason, ...(tx ? { tx } : {}), ...(env ? { env } : {}) });
  const expectedMerchant = identity(merchantId);
  if (typeof orderNumber !== "string" || !orderNumber || !["live", "test"].includes(mode)
      || (mode === "live" && !expectedMerchant)) {
    return pending("Falta el contexto verificado del intento (referencia, modo o comercio).");
  }
  if (mode === "live" && (typeof orderPrefix !== "string" || !/^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/.test(orderPrefix))) {
    return pending("El prefijo esperado del comercio no es válido.");
  }
  let expectedMinor;
  try {
    expectedMinor = amountMinor === undefined ? parseMinorCRC(amount ?? crcTotal) : amountMinor;
    formatMinorCRC(expectedMinor);
    if (expectedMinor <= 0) throw new Error("zero");
  } catch { return pending("El monto original del intento es inválido."); }
  if (explicitMissingOrder(data)) return { state: "not_found", explicitMissing: true };
  if (looksNotFound(data)) return { state: "not_found" };
  if (!validConsultEnvelope(data)) return pending("Respuesta de consult ilegible, incompleta o con error.");
  if (data.response.some((row) => !isObject(row))) return pending("consult contiene filas malformadas.");
  const mine = data.response.filter((row) => matchesOrderNumber(row.orderNumber, orderNumber, orderPrefix, mode));
  if (!mine.length) return pending("Las filas de consult no coinciden con la referencia y el prefijo esperados.");
  if (mine.some((row) => typeof row.type !== "string" || row.type.trim().toLowerCase() !== "payment")) {
    return pending("Hay modificaciones, reembolsos o tipos desconocidos; se requiere reconciliación.", mine[0]);
  }

  const validated = [];
  for (const row of mine) {
    const id = normalizeTransactionId(row.id_tilopay);
    const rowMerchant = identity(row.merchantId);
    const env = classifyEnvironment(row.environment);
    const code = (typeof row.code === "string" && row.code.trim())
      || (typeof row.code === "number" && Number.isSafeInteger(row.code) && row.code >= 0 ? String(row.code) : null);
    if (!id || (mode === "live" && !rowMerchant) || !env || !code || typeof row.currency !== "string" || !row.currency.trim()
        || typeof row.amount !== "string") return pending("Faltan campos transaccionales válidos en consult.", row, env);
    if (mode === "live" && rowMerchant !== expectedMerchant) return { state: "mismatch", tx: row, env, reason: "El comercio de la transacción no coincide con el intento." };
    if (row.currency.trim().toUpperCase() !== "CRC") return { state: "mismatch", tx: row, env, reason: "La moneda no coincide con CRC." };
    let paidMinor;
    try { paidMinor = parseMinorCRC(row.amount); } catch { return pending("El monto de consult no es un decimal válido.", row, env); }
    if (paidMinor !== expectedMinor) return { state: "mismatch", tx: row, env, reason: "El monto no coincide con el intento original." };
    if (env !== mode) return { state: "mismatch", tx: row, env, reason: "El entorno de la transacción no coincide con el intento." };
    const capture = typeof row.capture === "string" ? row.capture.trim().toLowerCase() : "";
    validated.push({ tx: { ...row, id_tilopay: id, merchantId: rowMerchant || "", amount: formatMinorCRC(paidMinor) }, id, env, code, capture, amountMinor: paidMinor });
  }
  const approved = validated.filter((row) => row.code === "1");
  if (!approved.length) return { state: "declined", tx: validated[0].tx, env: validated[0].env };
  if (new Set(approved.map((row) => row.id)).size !== 1) {
    return { state: "mismatch", tx: approved[0].tx, env: approved[0].env, reason: "Existen varios pagos aprobados distintos para el intento." };
  }
  const winner = approved[0];
  if (validated.some((row) => row.id === winner.id && (row.code !== winner.code || row.capture !== winner.capture))) {
    return pending("La misma transacción tiene resultados contradictorios en consult.", winner.tx, winner.env);
  }
  if (winner.capture === "authorize") return { state: "pending_capture", tx: winner.tx, env: winner.env, amountMinor: winner.amountMinor, reason: "La transacción está autorizada; falta confirmar su captura." };
  if (winner.capture !== "capture") return pending("La transacción no trae un estado de captura reconocido.", winner.tx, winner.env);
  return { state: "approved", tx: winner.tx, env: winner.env, amountMinor: winner.amountMinor };
}

